"""Static product-boundary checks; never import or execute scanned modules.

Resolve import aliases, not arbitrary runtime assignments or dynamic strings.
Stream JSON is restricted by default; string serialization is outside this policy.
"""

from __future__ import annotations

import ast
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[2]
PRODUCT_ROOTS = (
    "ai",
    "checkins",
    "communication",
    "core",
    "integrations",
    "messages",
    "notebook",
    "scheduler",
    "storage",
    "tasks",
    "ui",
    "user",
    "website",
)


def product_sources(root: Path = PROJECT_ROOT):
    """Yield product Python sources, excluding generated bytecode directories."""
    for package in PRODUCT_ROOTS:
        for path in sorted((root / package).rglob("*.py")):
            if "__pycache__" not in path.parts:
                yield (
                    path.relative_to(root).as_posix(),
                    path.read_text(encoding="utf-8-sig"),
                )
    for path in sorted(root.glob("*.py")):
        # The test runner is test infrastructure, not shipped application code.
        if path.name != "run_tests.py":
            yield path.name, path.read_text(encoding="utf-8-sig")


def imported_names(tree: ast.AST) -> dict[str, str]:
    """Map imported local names to their fully qualified names."""
    names = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                names[alias.asname or alias.name.split(".")[0]] = (
                    alias.name if alias.asname else alias.name.split(".")[0]
                )
        elif isinstance(node, ast.ImportFrom) and node.module:
            for alias in node.names:
                names[alias.asname or alias.name] = f"{node.module}.{alias.name}"
    return names


def qualified_name(node: ast.AST, names: dict[str, str]) -> str:
    """Resolve dotted attributes and imported aliases for a call target."""
    if isinstance(node, ast.Name):
        return names.get(node.id, node.id)
    if isinstance(node, ast.Attribute):
        return f"{qualified_name(node.value, names)}.{node.attr}"
    return ""


def calls_with_owners(tree: ast.AST):
    """Yield calls with enclosing class/function names for narrow exceptions."""

    def walk(node, owners):
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            owners = (*owners, node.name)
        if isinstance(node, ast.Call):
            yield node, ".".join(owners)
        for child in ast.iter_child_nodes(node):
            yield from walk(child, owners)

    yield from walk(tree, ())


def time_violations(source: str, path: str, allowed: dict[str, str]) -> list[str]:
    """Flag direct clock/format/parse calls outside documented approved files."""
    tree = ast.parse(source, filename=path)
    if allowed.get(path):
        return []
    names = imported_names(tree)
    violations = []
    for call, _ in calls_with_owners(tree):
        name = qualified_name(call.func, names)
        if name in {"datetime.datetime.now", "datetime.now"} or name.rsplit(".", 1)[
            -1
        ] in {"strftime", "strptime"}:
            violations.append(
                f"{path}:{call.lineno}: {name}; use core.time_utilities helpers"
            )
    return violations


def json_violations(
    source: str,
    path: str,
    allowed_files: dict[str, str],
    allowed_calls: dict[tuple[str, str, str], str],
) -> list[str]:
    """Reject stream JSON access unless its storage owner or exact call is approved."""
    tree = ast.parse(source, filename=path)
    if allowed_files.get(path):
        return []
    names = imported_names(tree)
    violations = []
    for call, owner in calls_with_owners(tree):
        name = qualified_name(call.func, names)
        if name in {"json.load", "json.dump"} and not allowed_calls.get(
            (path, owner, name)
        ):
            violations.append(
                f"{path}:{call.lineno}: {name} in {owner or '<module>'}; use approved storage/user-data helpers (or document a non-user-data exception)"
            )
    return violations


def core_ui_violations(source: str, path: str) -> list[str]:
    """Flag direct and literal dynamic UI imports from core, with no exceptions."""
    if not path.startswith("core/"):
        return []
    tree = ast.parse(source, filename=path)
    names = imported_names(tree)
    violations = []
    for node in ast.walk(tree):
        modules = []
        if isinstance(node, ast.Import):
            modules = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            # Resolve relative imports from the containing package.
            prefix = path.split("/")[: -node.level] if node.level else []
            base = ".".join([*prefix, *([node.module] if node.module else [])])
            modules = [
                base,
                *(f"{base}.{alias.name}".lstrip(".") for alias in node.names),
            ]
        elif isinstance(node, ast.Call) and qualified_name(node.func, names) in {
            "importlib.import_module",
            "__import__",
        }:
            if (
                node.args
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[0].value, str)
            ):
                modules = [node.args[0].value]
        if isinstance(node, (ast.Import, ast.ImportFrom, ast.Call)) and any(
            module == "ui" or module.startswith("ui.") for module in modules
        ):
            violations.append(
                f"{path}:{node.lineno}: core imports ui; move UI wiring to the UI/composition layer"
            )
    return violations
